// Records what the fixture bundles answer for their fixtures, as the cross-runtime reference.
//
// WHY a recorded file: the fixture graphs are synthetic, so there is no Python reference for their outputs.
// What must hold instead is that Node.js, Bun, Chromium and WebKit all produce the same answers from the same
// bundle; tests/unit and tests/browser compare against this file. Regenerate only after
// scripts/make-fixture-bundles.py changed a graph:  node scripts/fixture-expected.ts
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { loadVela } from "../src/node.ts";
import type { Answer, RGBImage } from "../src/types.ts";

const root = new URL("../tests/fixtures/bundles/", import.meta.url);
const names = ["span", "span_set", "ner", "relation", "evidence", "vision-span", "vision-ocr", "vision-box", "fast-decision", "fast-decision-split", "vision-decision"];
const out: {
  note: string;
  bundles: Record<string, { name: string; answer: Answer; inputTokens: number }[]>;
  images: Record<string, { width: number; height: number; sha256: string }>;
} = { note: "Generated by scripts/fixture-expected.ts from the fixture bundles; outputs of synthetic graphs.", bundles: {}, images: {} };
for (const name of names) {
  const dir = new URL(name + "/", root);
  const fixtures: { name: string; state?: unknown; question: any; images?: string[] }[] = JSON.parse(await readFile(new URL("fixtures.json", dir), "utf8"));
  const engine = await loadVela(dir.pathname);
  try {
    out.bundles[name] = [];
    for (const f of fixtures) {
      const images: RGBImage[] = [];
      for (const file of f.images ?? []) {
        const rgb = await engine.decodeImage(new URL(file, dir).pathname);
        images.push(rgb);
        out.images[`${name}/${file}`] = {
          width: rgb.width,
          height: rgb.height,
          sha256: createHash("sha256").update(rgb.data).digest("hex"),
        };
      }
      const r = await engine.systemOne({ state: f.state, questions: { q: f.question }, images });
      out.bundles[name].push({ name: f.name, answer: r.answers.q, inputTokens: r.usage.input_tokens });
    }
  } finally {
    await engine.dispose();
  }
}
await writeFile(new URL("expected.json", root), JSON.stringify(out, null, 1) + "\n");
console.log(`${new Date().toISOString()} INFO wrote tests/fixtures/bundles/expected.json bundles=${names.length}`);
