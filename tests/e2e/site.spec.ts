/** Text with less contrast than WCAG AA against what lies behind it: 4.5:1, or 3:1 for large text (24 px, or 18.66 px
 * bold). Backgrounds are the solid colors under the text, semi-transparent layers composited; a shader or gradient
 * counts as the solid color its element sets under it. */
const lowContrast = (page: Page) =>
  page.evaluate(() => {
    const ctx = document.createElement("canvas").getContext("2d", { willReadFrequently: true })!;
    const rgba = (c: string): number[] | null => {
      ctx.fillStyle = "#010203";
      ctx.fillStyle = c;
      if (ctx.fillStyle === "#010203" && !/^#010203|rgb\(1, 2, 3\)/.test(c)) return null;
      ctx.clearRect(0, 0, 1, 1);
      ctx.fillRect(0, 0, 1, 1);
      const [r, g, b, a] = ctx.getImageData(0, 0, 1, 1).data;
      return [r, g, b, a / 255];
    };
    const over = (top: number[], bottom: number[]) => [0, 1, 2].map((i) => top[i] * top[3] + bottom[i] * (1 - top[3])).concat(1);
    const lum = (c: number[]) => {
      const [r, g, b] = c.slice(0, 3).map((v) => (v / 255 <= 0.04045 ? v / 255 / 12.92 : ((v / 255 + 0.055) / 1.055) ** 2.4));
      return 0.2126 * r + 0.7152 * g + 0.0722 * b;
    };
    const background = (el: Element | null): number[] => {
      const layers: number[][] = [];
      for (; el; el = el.parentElement) {
        const c = rgba(getComputedStyle(el).backgroundColor);
        if (c && c[3] > 0) layers.push(c);
        if (c && c[3] === 1) break;
      }
      return layers.reverse().reduce((acc, layer) => over(layer, acc), [255, 255, 255, 1]);
    };
    const out: string[] = [];
    const skip = "template, script, style, svg, canvas, [hidden], .diagram, .chart, .sr-only, .dd-skip, [aria-hidden='true'], :disabled, .text-rotate";
    for (const el of document.querySelectorAll("body *")) {
      if (el.closest(skip)) continue;
      const text = [...el.childNodes].some((n) => n.nodeType === 3 && n.textContent!.trim());
      if (!text) continue;
      const box = el.getBoundingClientRect();
      const style = getComputedStyle(el);
      if (!box.width || !box.height || style.visibility === "hidden" || style.display === "none") continue;
      if (el.closest("details:not([open]) > :not(summary)")) continue;
      let fg = rgba(style.color);
      if (!fg) continue;
      let opacity = 1;
      for (let a: Element | null = el; a; a = a.parentElement) opacity *= Number(getComputedStyle(a).opacity);
      fg = [...fg.slice(0, 3), fg[3] * opacity];
      // Transparent text is a stand-in drawn by something else (an editor's textarea over its highlighted view).
      if (fg[3] === 0) continue;
      const bg = background(el);
      const [l1, l2] = [lum(over(fg, bg)), lum(bg)].sort((a, b) => b - a);
      const ratio = (l1 + 0.05) / (l2 + 0.05);
      const size = parseFloat(style.fontSize);
      const large = size >= 24 || (size >= 18.66 && Number(style.fontWeight) >= 700);
      if (ratio < (large ? 3 : 4.5)) out.push(`${el.tagName.toLowerCase()}.${[...el.classList].join(".")} "${el.textContent!.trim().slice(0, 30)}" ${ratio.toFixed(2)}`);
    }
    return out;
  });

for (const scheme of ["light", "dark"] as const)
  test(`text contrast meets WCAG AA in ${scheme} mode`, async ({ page }) => {
    const { assertClean } = guard(page);
    await page.emulateMedia({ colorScheme: scheme, reducedMotion: "reduce" });
    await page.goto("/docs/");
    await expect(page.locator("html")).toHaveAttribute("data-page-ready", "");
    // Every tab, since each answer kind has its own marks and tones.
    const found = new Set(await lowContrast(page));
    for (const id of TABS) {
      await page.locator(`#tab-${id}`).click();
      await expect(page.locator(`#panel-${id}`)).toBeVisible();
      for (const f of await lowContrast(page)) found.add(`${id}: ${f}`);
    }
    expect([...found]).toEqual([]);
    assertClean();
  });

