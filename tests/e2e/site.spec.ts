/** Click a tab's Run button and wait for the run; fails with the page's own error message. */
async function runTab(page: Page, tab: string) {
  await page.evaluate(() => delete document.documentElement.dataset.liveRun);
  await page.locator(`#run-${tab}`).click();
  await expect(page.locator("html")).toHaveAttribute("data-live-run", /done|failed/);
  // An empty error first, so a failed run reports the page's message instead of only "The run failed."
  await expect(page.locator(`#error-${tab}`)).toHaveText("");
  await expect(page.locator(`#status-${tab}`)).toHaveText(/^Done in/);
  await expect(page.locator(`#json-${tab}`)).toBeVisible();
  await expect(page.locator(`#json-${tab} code span[style*='--shiki-light']`).first()).toBeAttached();
  return JSON.parse((await page.locator(`#json-${tab} code`).textContent())!);
}

