test("the hero copy stays in its column in German, where long words and the rotating phrases met the side column", async ({ browser }) => {
  // Regression: at 1,024 to 1,100 px the phrase "offline, auf dem Gerät" ran into the recorded answer. One page per
  // width: resizing a loaded page makes WebKit report a ResizeObserver loop of the charts as a page error.
  for (const width of [1024, 1100, 1280]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    const { assertClean } = guard(page);
    await page.goto("/docs/?lang=de");
    await expect(page.locator("html")).toHaveAttribute("lang", "de");
    const { textRight, sideLeft } = await page.evaluate(() => {
      // Overflowing text leaves its box's rect unchanged, so measure the rendered text; screen-reader text is clipped.
      let right = 0;
      const walker = document.createTreeWalker(document.querySelector(".dd-hero-copy")!, NodeFilter.SHOW_TEXT);
      for (let n = walker.nextNode(); n; n = walker.nextNode()) {
        if (n.parentElement!.closest(".sr-only")) continue;
        const range = document.createRange();
        range.selectNodeContents(n);
        for (const rect of range.getClientRects()) if (rect.width) right = Math.max(right, rect.right);
      }
      return { textRight: right, sideLeft: document.querySelector(".dd-hero-side")!.getBoundingClientRect().left };
    });
    expect(textRight, `${width} px`).toBeLessThanOrEqual(sideLeft);
    assertClean();
    await page.close();
  }
});

test("a run fetches Brotli files with a bar per file and one for the run, and keeps its engine for the next run", async ({ page }) => {
  const { assertClean } = guard(page);
  const fetched: string[] = [];
  page.on("request", (r) => fetched.push(new URL(r.url()).pathname));
  await page.goto(EXAMPLES_URL);
  await page.locator("#tab-ner").click();
  // The bars hide when the run ends, so record what each visible one showed: "<bar>: <label> | <value>".
  await page.evaluate(() => {
    const box = document.getElementById("progress-ner")!;
    const seen: string[] = ((window as unknown as { seen: string[] }).seen = []);
    new MutationObserver(() => {
      if (box.hidden) return;
      for (const b of box.querySelectorAll<HTMLElement>("[data-bar]"))
        if (!b.hidden) seen.push(`${b.dataset.bar}: ${b.querySelector(".progress-label")!.textContent} | ${b.querySelector(".progress-value")!.textContent}`);
    }).observe(box, { attributes: true, subtree: true, childList: true, characterData: true });
  });
  await runTab(page, "ner");
  const bundle = "/models/vela3-fast-onnx/ner/q4/";
  expect(fetched).toEqual(expect.arrayContaining(["manifest.json.br", "task.onnx.br", "task.onnx.data.br"].map((f) => bundle + f)));
  expect(fetched.filter((p) => p.startsWith("/models/") && !p.endsWith(".br"))).toEqual([]);
  const seen: string[] = await page.evaluate(() => (window as unknown as { seen: string[] }).seen);
  expect(seen.some((s) => s.startsWith("file: Downloading task.onnx.data | "))).toBe(true);
  // The run's bar counts against the size downloadSize planned, with an estimate of the time left.
  expect(seen.some((s) => /^total: All downloads of this run \| [\d.,]+ of [\d.,]+ MB, (estimating the time left|about .+ left)$/.test(s))).toBe(true);
  await expect(page.locator("#progress-ner")).toBeHidden();
  await expect(page.locator("#status-ner")).toContainText("kept in memory for the next run");
  // The second run uses the engine in memory: nothing is fetched again.
  const before = fetched.length;
  await runTab(page, "ner");
  await expect(page.locator("#status-ner")).toContainText("already in memory");
  expect(fetched.slice(before).filter((p) => p.startsWith("/models/"))).toEqual([]);
  assertClean();
});

