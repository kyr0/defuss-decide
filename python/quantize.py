#!/usr/bin/env python3
"""Produce a separate weight-only INT8 bundle; reject probability/argmax regressions.

Default W8A32 stores signed per-channel MatMul weights and retains FP32 activations.
--mode dynamic enables ONNX Runtime activation quantization (failed our fast gate).
Activations remain mixed precision, embeddings/convolution may remain FP32.
This is a WASM/CPU target; it is not advertised as a WebGPU Q8 graph.
"""
import argparse,json,shutil
from pathlib import Path
import numpy as np
import onnxruntime as ort
ort.disable_telemetry_events()
from onnxruntime.quantization import quantize_dynamic,QuantType
from export import dump,session,run,softmax,fast_args,vision_args
import torch
from memguard import guard

def main():
    """Quantize a v0.1 decision bundle and write `manifest.json` only when Python ONNX Runtime keeps every fixture's
    probabilities within `--max-probability-error` and the same top option; otherwise exit nonzero. VERIFIED: both
    v0.1 candidates failed this gate (reports/quantization-rejected.json)."""
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--source',type=Path,required=True);ap.add_argument('--out',type=Path,required=True);ap.add_argument('--max-probability-error',type=float,default=.02);ap.add_argument('--mode',choices=['weight-only','dynamic'],default='weight-only')
    ap.add_argument('--min-free-gb',type=float,default=8.0,help='Stop the job when the machine has less memory available (python/memguard.py)')
    a=ap.parse_args();guard(a.min_free_gb);src=a.source.resolve();out=a.out.resolve()
    if src==out:ap.error('Use a new output directory')
    m=json.loads((src/'manifest.json').read_text());out.mkdir(parents=True,exist_ok=True);(out/'manifest.json').unlink(missing_ok=True)
    if not m['validated'] or m['precision']!='fp32':raise ValueError('Expected validated FP32 bundle')
    for p in src.iterdir():
        if (p.name in ['tokenizer.json','tokenizer_config.json','fixtures.json'] or p.suffix=='.png' or p.name.startswith('LICENSE')):shutil.copyfile(p,out/p.name)
    for name,g in m['graphs'].items():
        print('Quantizing '+name,flush=True)
        if a.mode=='dynamic':
            quantize_dynamic(str(src/g['file']),str(out/g['file']),weight_type=QuantType.QInt8,per_channel=True,op_types_to_quantize=['MatMul'],extra_options={'MatMulConstBOnly':True})
        else:
            from vela_onnx.weight_only import quantize_weights
            quantize_weights(src/g['file'],out/g['file'])
        g['externalData']=[];g['sizeBytes']=(out/g['file']).stat().st_size
    # JS validator additionally validates rendering and image preprocessing. Python
    # checks real graph behavior over identical tensors generated by pinned code.
    fixtures=json.loads((src/'fixtures.json').read_text());ref=session(src/'decision.onnx');quant=session(out/'decision.onnx');report=[]
    for f in fixtures:
        if m['kind']=='fast':
            inputs=fast_args({'ids':f['ids'],'pool':f['pool'],'opt_pos':f['optionPositions']})
        else:
            # Reuse exact processor pixel arrays saved by export.py.
            pixel_path=src/(f['name']+'-pixels.npy')
            if f['images'] and not pixel_path.exists():raise FileNotFoundError(f'Re-export vision bundle to create {pixel_path.name}')
            if f['images']:
                vs=session(src/'vision.onnx');vq=session(out/'vision.onnx');pixels=np.load(pixel_path)
                rf=np.concatenate([vs.run(None,{'pixel_values':p[None]})[0] for p in pixels],0).reshape(-1,768)
                qf=np.concatenate([vq.run(None,{'pixel_values':p[None]})[0] for p in pixels],0).reshape(-1,768)
                del vs,vq
            else:rf=qf=np.zeros((1,768),np.float32)
            ex={'input_ids':f['ids'],'spans':f['spans']}
            inputs=vision_args(ex,torch.from_numpy(rf),m['imageId'])
        r=run(ref,inputs)
        if m['kind']=='vision':inputs=vision_args(ex,torch.from_numpy(qf),m['imageId'])
        q=run(quant,inputs);rp,qp=softmax(r),softmax(q);err=float(np.max(abs(rp-qp)))
        if not np.isfinite(q).all() or err>a.max_probability_error or np.argmax(q)!=np.argmax(r):
            dump(out/'parity-quantization.json',{'passed':False,'mode':a.mode,'failed_case':f['name'],'max_probability_error':err,'tolerance':a.max_probability_error,'argmax_equal':bool(np.argmax(q)==np.argmax(r))})
            raise AssertionError(f'{f["name"]}: quantization gate failed, error={err}')
        report.append({'case':f['name'],'max_probability_error':err,'argmax_equal':True})
    m['precision']='w8a32' if a.mode=='weight-only' else 'q8';m['validated']=True;m['quantization']=a.mode+' per-channel signed MatMul';m['recommendedBackend']='wasm'
    dump(out/'parity-quantization.json',{'passed':True,'tolerance':a.max_probability_error,'checks':report,'note':'Small parity suite; not an accuracy benchmark or general quality guarantee.'});dump(out/'manifest.json',m)
    print(json.dumps({'passed':True,'out':str(out),'checks':report}),flush=True)
if __name__=='__main__':main()
